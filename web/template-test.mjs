// Serve built web/ first. Optional: BASE_URL, PLAYWRIGHT_MODULE, CHROMIUM_EXECUTABLE.
import assert from 'node:assert/strict';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? 'playwright');
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_EXECUTABLE, headless: true, args: ['--no-sandbox', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1400, height: 1000 } });
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
const status = (text) => page.waitForFunction((text) => document.querySelector('#status').textContent === text, text, { timeout: 60_000 });
try {
  await page.goto(process.env.BASE_URL ?? 'http://localhost:8000');
  const source = page.locator('#source');
  const template = page.getByRole('button', { name: 'Pygame template', exact: true });
  assert.equal(await template.isVisible(), true);
  assert.match(await page.locator('#editor-title').getAttribute('class'), /sr-only/, 'filename must not occupy the syntax toolbar');
  await page.locator('#syntax-toggle').click();
  await source.fill('old_value = 1');
  await page.locator('#gutter button[data-line="1"]').click();
  await page.locator('#gutter [data-condition-line="1"]').click();
  await page.locator('#breakpoint-condition').fill('True');
  await page.getByRole('button', { name: 'Save condition', exact: true }).click();
  await template.click();
  const code = await source.inputValue();
  assert.deepEqual(await source.evaluate((element) => [element.selectionStart, element.selectionEnd, element.scrollTop, element.scrollLeft]), [0, 0, 0, 0], 'template should reset the caret and viewport');
  assert.match(code, /^import pygame\n/);
  assert.match(code, /def main\(\):/);
  assert.match(code, /pygame\.display\.set_mode/);
  assert.match(code, /while not quit:/, 'template must use valid Python rather than !quit');
  assert.match(code, /pygame\.event\.get\(\)/);
  assert.match(code, /pygame\.QUIT/);
  assert.match(code, /pygame\.K_ESCAPE/);
  assert(code.indexOf('clock.tick(60)') < code.indexOf('# Draw here.'));
  assert(code.indexOf('# Draw here.') < code.indexOf('pygame.display.flip()'));
  assert.match(code, /pygame\.quit\(\)/);
  assert.match(code, /main\(\)\s*$/);
  assert.doesNotMatch(code, /old_value/);
  assert.equal(await page.locator('#gutter .breakpoint').count(), 0);
  assert.equal(await page.locator('#gutter .breakpoint-condition').count(), 0);
  assert.equal(await page.locator('#examples').inputValue(), 'template');
  assert.equal(await page.locator('#syntax-code').textContent(), code + '\n');
  assert.equal(await page.locator('#viewport iframe').count(), 0, 'creating a template should not run it');
  await page.waitForFunction(() => document.querySelector('#source').dataset.syntaxState === 'valid', null, { timeout: 60_000 });
  await page.reload();
  assert.equal(await source.inputValue(), code, 'template and selection must be saved');
  assert.equal(await page.locator('#examples').inputValue(), 'template');
  await page.locator('#run').click();
  await status('Running');
  const canvas = page.frameLocator('#viewport iframe').locator('canvas');
  await canvas.waitFor();
  await canvas.click();
  await page.keyboard.down('Escape');
  await page.waitForTimeout(150);
  await page.keyboard.up('Escape');
  await status('Finished');
  assert.equal(await page.locator('#console').textContent(), '', 'template must run and shut down without errors');
  await page.locator('#debug').click();
  await page.waitForFunction(() => !document.querySelector('#debug-break').disabled, null, { timeout: 60_000 });
  assert.equal(await template.isDisabled(), true, 'template replacement must be locked during debugging');
  await page.locator('#debug-break').click();
  await page.waitForFunction(() => document.querySelector('#status').dataset.state === 'paused');
  assert.equal(await template.isDisabled(), true);
  assert.equal(await source.inputValue(), code);
  await page.locator('#debug-stop').click();
  await status('Stopped');
  assert.equal(await template.isDisabled(), false);
  await source.fill('changed = 1');
  await page.locator('#reset').click();
  assert.equal(await source.inputValue(), code, 'Reset example should reload the selected template');
  assert.deepEqual(errors, []);
  console.log('Pygame template browser tests passed');
} finally {
  await browser.close();
}
