// Serve built web/ first. Optional: BASE_URL, PLAYWRIGHT_MODULE, CHROMIUM_EXECUTABLE.
import assert from 'node:assert/strict';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? 'playwright');
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_EXECUTABLE, headless: true, args: ['--no-sandbox', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1400, height: 1000 } });
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
const upper = page.locator('#runtime-debug-divider');
const lower = page.locator('#console-divider');
const status = (text) => page.waitForFunction((text) => document.querySelector('#status').textContent === text, text, { timeout: 60_000 });
const heights = () => page.evaluate(() => ['viewport', 'debugger', 'console-pane'].map((id) => document.getElementById(id).getBoundingClientRect().height));
const near = (a, b, message) => assert(Math.abs(a - b) < 2, `${message}: ${a} vs ${b}`);
async function drag(divider, delta) {
  await divider.scrollIntoViewIfNeeded();
  const box = await divider.boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2 + delta, { steps: 12 });
  await page.mouse.up();
  assert.equal(await page.locator('body').evaluate((body) => body.classList.contains('resizing-results')), false);
}
try {
  await page.goto(process.env.BASE_URL ?? 'http://localhost:8000');
  assert.equal(await upper.isVisible(), false);
  assert.equal(await lower.getAttribute('aria-label'), 'Resize runtime and console');
  const initial = await heights();
  await page.locator('#run').click();
  await status('Running');
  await page.waitForFunction(() => document.querySelector('#console').textContent.includes('Hello!'), null, { timeout: 60_000 });
  await page.evaluate(() => { window.originalRuntimeFrame = document.querySelector('#viewport iframe'); });
  await drag(lower, -90);
  let resized = await heights();
  near(resized[0], initial[0] - 90, 'dragging upward shrinks runtime');
  near(resized[2], initial[2] + 90, 'dragging upward grows console');
  assert(await page.evaluate(() => window.originalRuntimeFrame === document.querySelector('#viewport iframe')), 'resizing must not replace the running iframe');
  assert.equal(await page.locator('#status').textContent(), 'Running');
  await lower.press('Home');
  near((await heights())[0], 100, 'runtime minimum');
  await lower.press('End');
  near((await heights())[2], 80, 'console minimum');
  await lower.dblclick();
  near((await heights())[0], initial[0], 'double-click resets sizes');
  await drag(lower, -60);
  const normal = await heights();
  await page.reload();
  near((await heights())[0], normal[0], 'normal split persists on reload');
  near((await heights())[2], normal[2], 'console split persists on reload');

  await page.locator('#source').fill('def f():\n    a = 1\n    b = 2\n    return a + b\nvalue = f()\nprint(value)');
  await page.locator('#gutter button[data-line="3"]').click();
  await page.locator('#debug').click();
  await status('Paused at line 3');
  assert.equal(await upper.isVisible(), true);
  assert.equal(await lower.getAttribute('aria-label'), 'Resize debugger and console');
  const debugInitial = await heights();
  await drag(upper, 60);
  resized = await heights();
  near(resized[0], debugInitial[0] + 60, 'upper handle grows runtime');
  near(resized[1], debugInitial[1] - 60, 'upper handle shrinks debugger');
  near(resized[2], debugInitial[2], 'upper handle leaves console unchanged');
  const beforeLower = await heights();
  await drag(lower, 45);
  resized = await heights();
  near(resized[0], beforeLower[0], 'lower handle leaves runtime unchanged');
  near(resized[1], beforeLower[1] + 45, 'lower handle grows debugger');
  near(resized[2], beforeLower[2] - 45, 'lower handle shrinks console');
  await lower.press('End');
  near((await heights())[2], 80, 'console still enforces its minimum while debugging');
  assert(await page.locator('.debug-inspection').evaluate((element) => element.clientHeight > 180), 'debugger inspector can grow beyond its old fixed height');
  const beforeFrameSwitch = await heights();
  await page.locator('#call-stack [data-frame-id="1"]').click();
  await page.waitForFunction(() => document.querySelector('#call-stack [data-frame-id="1"]')?.getAttribute('aria-pressed') === 'true');
  for (const [i, height] of (await heights()).entries()) near(height, beforeFrameSwitch[i], 'frame/variable updates preserve resized layout');
  assert.equal(await page.locator('#status').textContent(), 'Paused at line 3');
  await upper.press('Home');
  near((await heights())[0], 100, 'runtime minimum while debugging');
  await upper.press('End');
  const minDebugger = await page.locator('#debugger > .console-heading').evaluate((element) => Math.ceil(element.getBoundingClientRect().height) + 60);
  near((await heights())[1], minDebugger, 'debugger keeps header and usable inspector space');
  await lower.dblclick();
  for (const [i, height] of (await heights()).entries()) near(height, debugInitial[i], 'debug reset');
  await drag(lower, -40);
  const debugSaved = await heights();
  await page.locator('#run').click();
  await status('Finished');
  near((await heights())[0], normal[0], 'hiding debugger restores independent normal sizes');
  near((await heights())[2], normal[2], 'normal console size is independent');
  await page.reload();
  await page.locator('#gutter button[data-line="3"]').click();
  await page.locator('#debug').click();
  await status('Paused at line 3');
  for (const [i, height] of (await heights()).entries()) near(height, debugSaved[i], 'debug sizes persist across reload');

  await lower.evaluate((element) => element.addEventListener('pointerdown', (event) => { window.resizePointer = event.pointerId; }, { once: true }));
  const cancelBox = await lower.boundingBox();
  await page.mouse.move(cancelBox.x + cancelBox.width / 2, cancelBox.y + 4);
  await page.mouse.down();
  await page.mouse.move(cancelBox.x + cancelBox.width / 2, cancelBox.y + 14);
  await lower.evaluate((element) => element.dispatchEvent(new PointerEvent('pointercancel', { pointerId: window.resizePointer })));
  await page.mouse.up();
  assert.equal(await page.locator('body').evaluate((element) => element.classList.contains('resizing-results')), false, 'cancelled drags must release resize mode');
  assert.notEqual(await page.locator('#viewport iframe').evaluate((element) => getComputedStyle(element).pointerEvents), 'none', 'cancelled drags must restore runtime interaction');

  // Narrow/mobile layouts still expose the same vertical resize controls.
  await page.setViewportSize({ width: 600, height: 900 });
  const mobileBefore = await heights();
  await lower.press('ArrowUp');
  const mobileAfter = await heights();
  near(mobileAfter[1], mobileBefore[1] - 10, 'mobile keyboard resize');
  near(mobileAfter[2], mobileBefore[2] + 10, 'mobile console resize');
  assert.equal(await page.locator('#status').textContent(), 'Paused at line 3');
  await page.locator('#debug-stop').click();
  await status('Stopped');
  await page.setViewportSize({ width: 1400, height: 320 });
  await page.waitForTimeout(50);
  assert(await page.locator('#result-windows').evaluate((element) => element.scrollHeight > element.clientHeight), 'short windows must scroll instead of clipping panes below their minimums');
  assert((await heights())[0] >= 99 && (await heights())[2] >= 79);
  assert.deepEqual(errors, []);
  console.log('Vertical result pane resize browser tests passed');
} finally {
  await browser.close();
}
